export function quoteCopy(locale) {
  return copy[String(locale || 'hy').split('-')[0]] || copy.hy
}

// Whole drams with thin grouping: 18060 → "18 060 ֏".
export function formatMoney(value) {
  if (
    value === null ||
    value === undefined ||
    value === '' ||
    Number.isNaN(Number(value))
  )
    return '—'
  const rounded = String(Math.round(Number(value)))
  return `${rounded.replace(/\B(?=(\d{3})+(?!\d))/g, ' ')} ֏`
}

export function serviceName(workshop, locale) {
  const value = String(workshop?.value || '')
    .trim()
    .toUpperCase()
  return quoteCopy(locale).services[value] || workshop?.name || ''
}

export function statusTone(status) {
  return (
    {
      draft: 'slate',
      submitted: 'amber',
      quoted: 'blue',
      accepted: 'emerald',
      declined: 'slate',
      rejected: 'rose',
      cancelled: 'slate',
    }[status] || 'slate'
  )
}

// One line per reason; a draft can be waiting on more than one thing.
export function reasonsText(reasons, locale) {
  const t = quoteCopy(locale).reasons
  const list = Array.isArray(reasons) ? reasons : []
  // An outline that does not close is the one thing the customer can fix in the
  // drawing, so it is said even when the manager prices everything. "disabled"
  // already says the manager prices everything, and a file without a flat
  // drawing is never priced instantly, so nothing else is worth asking for.
  if (list.includes('open')) return [t.open]
  if (list.includes('disabled')) return [t.disabled]
  if (list.includes('drawing')) return [t.drawing]
  return list.map((reason) => t[reason]).filter(Boolean)
}

// Only the fields a customer edits; the server works out the rest.
export function itemPayload(item) {
  return {
    workshop_ids: (item.workshop_ids || []).map(Number),
    pricing_thickness_id: item.pricing_thickness_id
      ? Number(item.pricing_thickness_id)
      : null,
    material: item.pricing_thickness_id
      ? null
      : String(item.material || '').trim() || null,
    thickness:
      item.pricing_thickness_id ||
      item.thickness === '' ||
      item.thickness === null ||
      item.thickness === undefined
        ? null
        : Number(item.thickness),
    quantity: Math.max(1, Math.round(Number(item.quantity) || 1)),
    bends:
      item.bends === '' || item.bends === null || item.bends === undefined
        ? null
        : Math.max(0, Math.round(Number(item.bends))),
    paint_ral: String(item.paint_ral || '').trim() || null,
    primer_required: Boolean(item.primer_required),
    note: String(item.note || '').trim() || null,
  }
}

export function fileSize(bytes) {
  const size = Number(bytes) || 0
  if (size >= 1048576) return `${(size / 1048576).toFixed(1)} MB`
  return `${Math.max(1, Math.round(size / 1024))} KB`
}
