const loadRank = (operator) => [
  Number(operator?.active_tasks) || 0,
  Number(operator?.overdue_tasks) || 0,
  Number(operator?.urgent_tasks) || 0,
]

// The operator with the lightest load: fewest open jobs, then fewest overdue,
// then fewest urgent ones, then by name so the answer never flickers.
export function leastBusyOperator(operators = []) {
  return (
    [...(operators || [])].sort((a, b) => {
      const left = loadRank(a)
      const right = loadRank(b)
      for (let i = 0; i < left.length; i += 1)
        if (left[i] !== right[i]) return left[i] - right[i]
      return String(a?.name || '').localeCompare(String(b?.name || ''))
    })[0] || null
  )
}

// The operators of one workshop, with the live counts when they are loaded.
export function workshopOperators(factory, workload) {
  return (
    workload?.factories?.find((item) => Number(item.id) === Number(factory?.id))
      ?.operators ||
    factory?.operators ||
    []
  )
}

// { [factoryId]: operatorId | null }: the least busy operator of every workshop.
export function balancedAssignments(factories = [], workload = null) {
  const result = {}
  for (const factory of factories || [])
    result[factory.id] =
      leastBusyOperator(workshopOperators(factory, workload))?.id ?? null
  return result
}

export function canManageTask(user, task, allowed) {
  return Boolean(
    allowed &&
      (['admin', 'manager'].includes(user?.role?.name) ||
        (user?.role?.name === 'engineer' &&
          String(user.id) === String(task?.creator_id)))
  )
}

export function assignmentLocked(step) {
  return Boolean(
    step?.completed_at ||
      step?.awaiting_engineer_confirmation ||
      ['finished', 'completed', 'done', 'canceled', 'cancelled'].includes(
        step?.status
      )
  )
}

export function operatorWorkloadLabel(operator, locale = 'hy') {
  const t = routingCopy[locale] || routingCopy.hy
  if (operator.active_tasks == null) return operator.name
  return `${operator.name} · ${t.active}: ${operator.active_tasks} · ${
    t.overdue
  }: ${operator.overdue_tasks || 0}`
}

export function taskFiles(task) {
  const files = new Map()
  for (const selected of task?.selected_files || []) {
    if (selected.pmp_file?.id)
      files.set(selected.pmp_file.id, {
        ...selected.pmp_file,
        quantity: selected.quantity || 1,
        task_file_revision_id: selected.task_file_revision_id || null,
      })
  }
  for (const step of task?.factory_orders || [])
    for (const file of step.files || []) {
      if (!files.has(file.id))
        files.set(file.id, { ...file, quantity: file.pivot?.quantity || 1 })
    }
  return [...files.values()]
}

export function sortWorkshopTasks(tasks, factoryId) {
  const step = (order) =>
    (order.factory_orders || []).find(
      (row) => String(row.factory_id) === String(factoryId)
    ) || {}
  const rank = { urgent: 2, high: 1, normal: 0 }
  const deadline = (order, row) => {
    const date = Date.parse(row.deadline || order.dates?.finish_date || '')
    return Number.isFinite(date) ? date : Infinity
  }
  return [...tasks].sort((a, b) => {
    const left = step(a)
    const right = step(b)
    return (
      (rank[right.priority] || 0) - (rank[left.priority] || 0) ||
      (deadline(a, left) === deadline(b, right)
        ? 0
        : deadline(a, left) - deadline(b, right))
    )
  })
}
