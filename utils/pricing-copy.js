export function pricingCopy(locale) {
  return copy[String(locale || 'hy').split('-')[0]] || copy.hy
}

export const SERVICE_FIELDS = [
  'bend_price',
  'paint_price_m2',
  'primer_price_m2',
  'paint_min_part',
  'setup_fee',
  'min_order',
  'waste_percent',
]

// The whole list as the server takes it, numbers as numbers.
export function pricingPayload(state) {
  const n = (value) =>
    value === '' || value === null || value === undefined ? 0 : Number(value)
  return {
    settings: {
      enabled: Boolean(state.settings.enabled),
      ...Object.fromEntries(
        SERVICE_FIELDS.map((key) => [key, n(state.settings[key])])
      ),
      discounts: (state.settings.discounts || []).map((tier) => ({
        min_qty: Math.round(n(tier.min_qty)),
        percent: n(tier.percent),
      })),
      vat_included: Boolean(state.settings.vat_included),
      customer_note: String(state.settings.customer_note || '').trim() || null,
    },
    materials: (state.materials || []).map((material) => ({
      id: material.id || null,
      name: String(material.name || '').trim(),
      density: n(material.density),
      price_per_kg: n(material.price_per_kg),
      is_active: Boolean(material.is_active),
      thicknesses: (material.thicknesses || []).map((row) => ({
        id: row.id || null,
        thickness: n(row.thickness),
        cut_price_per_m: n(row.cut_price_per_m),
        pierce_price: n(row.pierce_price),
        is_active: Boolean(row.is_active),
      })),
    })),
  }
}
